"""Synthetic question-answer pairs from train-split risk paragraphs (FL-M2 T14).

Every pair is generated by a local open-weight model (Qwen/Qwen3-4B-AWQ, Apache-2.0), marked
synthetic=true and split=train, and is never used for evaluation. Three steps:

    uv run python -m filinglens.extract.synthetic_qa prepare      # sample paragraphs (main env)
    ~/venvs/fl-gpu/bin/python -m filinglens.extract.synthetic_qa generate \
        --model Qwen/Qwen3-4B-AWQ --gpu-memory-utilization 0.80 --enforce-eager
    uv run python -m filinglens.extract.synthetic_qa finalize     # check, leakage test (main env)

Leakage: paragraphs come only from train-split companies, and a paragraph whose text also
appears at any dev or test company (copied boilerplate) is dropped before sampling. finalize
checks both again and refuses to write the output if either count isn't zero.

Checks on every pair (failures are dropped, and counted in bench/synthetic_qa.json):
the evidence is a verbatim quote (ignoring case) from the paragraph or its heading; at least half
of the answer's content words appear there; the question names the ticker, ends with "?", and
doesn't copy 8 words in a row from them; the two questions of a paragraph differ. The evidence
check proves the quote is grounded, not that the answer is fully right.

Top-level imports are standard library only: the generate step runs in the GPU environment.
"""

import argparse
import hashlib
import json
import random
import re
import sys
import time
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path

PROMPT = Path("docs/labeling/synthetic_qa_prompt.md")
PROMPT_VERSION = 2  # v2: ticker required in every question; heading may be quoted
WORK = Path("data/interim/synthetic")
TASKS = WORK / "qa_tasks.jsonl"
OUTPUT = Path("gold/synthetic/risk_qa.train.jsonl")
SEED = 20261119
PER_CELL = 14  # 6 sectors x 5 years x 14 = 420 paragraphs
TYPES = ["factual", "cause", "impact", "mitigation"]
COPY_NGRAM = 8
STOPWORDS = frozenset(
    "a an and are as at be by can could do for from has have if in into is it its may might"
    " not of on or our such that the their these this to us we which will with would".split()
)
WORD = re.compile(r"[a-z0-9]+")


# ---------- shared helpers ----------


def text_key(text: str) -> str:
    """Hash of the text with case and whitespace normalized: finds boilerplate copies."""
    return hashlib.sha256(" ".join(text.lower().split()).encode()).hexdigest()


def squash(text: str) -> str:
    """Lower case, whitespace collapsed, curly quotes straightened: for the evidence check."""
    table = str.maketrans({"’": "'", "‘": "'", "“": '"', "”": '"'})
    return " ".join(text.translate(table).lower().split())


def source(task: dict) -> str:
    """What a pair may quote: the risk's heading (its one-line summary in the 10-K) and text."""
    return f"{task.get('heading') or ''}\n{task['text']}"


def words(text: str) -> list[str]:
    return WORD.findall(text.lower())


def content_words(text: str) -> set[str]:
    return {w for w in words(text) if w not in STOPWORDS}


def mentions(text: str, ticker: str) -> bool:
    """The ticker as a whole word, case-insensitive ("BRK-B" counts; "XOMS" for XOM doesn't)."""
    pattern = rf"(?<![A-Za-z0-9]){re.escape(ticker)}(?![A-Za-z0-9])"
    return re.search(pattern, text, flags=re.IGNORECASE) is not None


def ngrams(tokens: list[str], n: int) -> set[tuple[str, ...]]:
    return {tuple(tokens[i : i + n]) for i in range(len(tokens) - n + 1)}


def read_jsonl(path: Path) -> list[dict]:
    with path.open() as f:
        return [json.loads(line) for line in f if line.strip()]


def write_jsonl(rows: list[dict], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))


# ---------- prepare (main environment) ----------


def draw(pool: list[dict], per_cell: int, seed: int) -> list[dict]:
    """Up to `per_cell` paragraphs per (sector, year), at most one per filing, seeded."""
    rng = random.Random(seed)
    cells: dict[tuple[str, int], list[dict]] = {}
    for row in sorted(pool, key=lambda r: r["para_id"]):
        cells.setdefault((row["sector"], int(row["period_year"])), []).append(row)
    picked = []
    for cell in sorted(cells):
        rows = cells[cell][:]
        rng.shuffle(rows)
        used: set[str] = set()
        for row in rows:
            if row["accession"] in used:
                continue
            used.add(row["accession"])
            picked.append(row)
            if len(used) == per_cell:
                break
    return picked


def prepare(corpus, splits, per_cell: int = PER_CELL, seed: int = SEED) -> tuple[list, dict]:
    """Tasks from train companies, with dev/test boilerplate removed. Takes pandas DataFrames."""
    from filinglens.extract.gold_sample import eligible

    train = set(splits.loc[splits["split"] == "train", "cik"].astype(int))
    held = set(splits.loc[splits["split"] != "train", "cik"].astype(int))
    held_keys = set(corpus.loc[corpus["cik"].isin(held), "text"].map(text_key))
    pool = eligible(corpus)
    pool = pool[pool["cik"].isin(train)]
    keys = pool["text"].map(text_key)
    shared = int(keys.isin(held_keys).sum())
    pool = pool[~keys.isin(held_keys)]
    columns = ["para_id", "cik", "ticker", "sector", "period_year", "accession", "heading", "text"]
    picked = draw(pool[columns].to_dict("records"), per_cell, seed)
    tasks = [
        {
            "task_no": i,
            **{k: (int(r[k]) if k in ("cik", "period_year") else r[k]) for k in columns},
            "text_key": text_key(r["text"]),
        }
        for i, r in enumerate(picked, start=1)
    ]
    stats = {
        "train_companies": len(train),
        "held_out_companies": len(held),
        "eligible_train_paragraphs": int(len(pool) + shared),
        "dropped_text_also_at_dev_or_test_company": shared,
        "tasks": len(tasks),
        "task_companies": len({t["cik"] for t in tasks}),
        "by_sector": dict(sorted(Counter(t["sector"] for t in tasks).items())),
        "by_year": dict(sorted(Counter(str(t["period_year"]) for t in tasks).items())),
    }
    return tasks, stats


# ---------- generate (GPU environment) ----------


def schema() -> dict:
    pair = {
        "type": "object",
        "properties": {
            "question": {"type": "string"},
            "answer": {"type": "string"},
            "evidence": {"type": "string"},
            "type": {"type": "string", "enum": TYPES},
        },
        "required": ["question", "answer", "evidence", "type"],
        "additionalProperties": False,
    }
    return {
        "type": "object",
        "properties": {"pair_1": pair, "pair_2": pair},
        "required": ["pair_1", "pair_2"],
        "additionalProperties": False,
    }


def user_message(task: dict) -> str:
    heading = task.get("heading") or "(none)"
    return (
        f"Ticker: {task['ticker']}\nFiscal year: FY{task['period_year']}\n"
        f"Heading: {heading}\n\nPARAGRAPH:\n{task['text']}"
    )


def messages(task: dict, system_prompt: str) -> list[dict]:
    return [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_message(task)},
    ]


def generate(tasks: list[dict], args: argparse.Namespace, system_prompt: str) -> list[str]:
    """Greedy, schema-constrained output from vLLM, in task order."""
    from vllm import LLM, SamplingParams
    from vllm.sampling_params import StructuredOutputsParams

    llm = LLM(
        model=args.model,
        quantization=args.quantization,
        max_model_len=args.max_model_len,
        gpu_memory_utilization=args.gpu_memory_utilization,
        enforce_eager=args.enforce_eager,
        seed=0,
    )
    params = SamplingParams(
        temperature=0.0,
        max_tokens=600,
        structured_outputs=StructuredOutputsParams(json=schema()),
    )
    outputs = llm.chat(
        [messages(t, system_prompt) for t in tasks],
        params,
        chat_template_kwargs={"enable_thinking": False},
    )
    return [o.outputs[0].text for o in outputs]


# ---------- finalize (main environment) ----------


def check_pair(pair: dict, task: dict, other_question: str | None) -> list[str]:
    """Problems with one pair; an empty list means it is kept."""
    problems = []
    question, answer, evidence = (
        pair.get(k, "").strip() for k in ("question", "answer", "evidence")
    )
    q_words, a_words, e_words = words(question), words(answer), words(evidence)
    if not question.endswith("?") or not 6 <= len(q_words) <= 40:
        problems.append("question_form")
    if not mentions(question, task["ticker"]):
        problems.append("question_no_ticker")
    src = source(task)
    if ngrams(q_words, COPY_NGRAM) & ngrams(words(src), COPY_NGRAM):
        problems.append("question_copies_paragraph")
    if not 1 <= len(a_words) <= 40:
        problems.append("answer_length")
    if not 5 <= len(e_words) <= 40:
        problems.append("evidence_length")
    parts = (task.get("heading") or "", task["text"])  # a quote may not span the two
    if not evidence or not any(squash(evidence) in squash(part) for part in parts):
        problems.append("evidence_not_verbatim")
    answer_cw = content_words(answer) - {task["ticker"].lower()}
    if answer_cw and len(answer_cw & content_words(src)) / len(answer_cw) < 0.5:
        problems.append("answer_not_from_paragraph")
    if pair.get("type") not in TYPES:
        problems.append("type")
    if other_question is not None and words(other_question) == q_words:
        problems.append("duplicate_question")
    return problems


def check_task(task: dict, raw: str) -> list[dict]:
    """Both pairs of one task with their problems. Unparseable output gives two failed pairs."""
    try:
        answer = json.loads(raw)
        pairs = [answer["pair_1"], answer["pair_2"]]
    except (json.JSONDecodeError, KeyError, TypeError):
        return [{"k": k, "problems": ["unparseable"], "pair": {}} for k in (1, 2)]
    out = []
    for k, pair in enumerate(pairs, start=1):
        other = pairs[0].get("question") if k == 2 else None
        out.append({"k": k, "problems": check_pair(pair, task, other), "pair": pair})
    return out


def leakage(rows: list[dict], train_ciks: set[int], held_keys: set[str], tasks: dict) -> dict:
    return {
        "rows_from_non_train_companies": sum(r["cik"] not in train_ciks for r in rows),
        "rows_with_source_text_at_dev_or_test_company": sum(
            tasks[r["para_id"]]["text_key"] in held_keys for r in rows
        ),
        "rows_not_marked_synthetic_train": sum(
            not (r["synthetic"] is True and r["split"] == "train") for r in rows
        ),
    }


def build_rows(tasks: list[dict], raws: dict[int, str], generator: str) -> tuple[list, list]:
    kept, checked = [], []
    for task in tasks:
        for result in check_task(task, raws[task["task_no"]]):
            pair = result["pair"]
            checked.append({"task_no": task["task_no"], "para_id": task["para_id"], **result})
            if result["problems"]:
                continue
            kept.append(
                {
                    "qa_id": f"{task['para_id']}:q{result['k']}",
                    "synthetic": True,
                    "split": "train",
                    "generator": generator,
                    "prompt_version": PROMPT_VERSION,
                    "cik": task["cik"],
                    "ticker": task["ticker"],
                    "sector": task["sector"],
                    "period_year": task["period_year"],
                    "para_id": task["para_id"],
                    "type": pair["type"],
                    "question": pair["question"].strip(),
                    "answer": pair["answer"].strip(),
                    "evidence": pair["evidence"].strip(),
                }
            )
    return kept, checked


# ---------- command line ----------


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("prepare")
    p.add_argument("--corpus", type=Path, default=Path("data/interim/risk_paragraphs.parquet"))
    p.add_argument("--splits", type=Path, default=Path("gold/splits.csv"))
    g = sub.add_parser("generate")
    g.add_argument("--model", required=True)
    g.add_argument("--quantization", default=None)
    g.add_argument("--limit", type=int, default=None, help="first N tasks (smoke test)")
    g.add_argument("--max-model-len", type=int, default=4096)
    g.add_argument("--gpu-memory-utilization", type=float, default=0.80)
    g.add_argument("--enforce-eager", action="store_true")
    f = sub.add_parser("finalize")
    f.add_argument("--corpus", type=Path, default=Path("data/interim/risk_paragraphs.parquet"))
    f.add_argument("--splits", type=Path, default=Path("gold/splits.csv"))
    f.add_argument("--model", default="Qwen/Qwen3-4B-AWQ")
    argv = sys.argv[1:] if argv is None else argv
    args = parser.parse_args(argv)
    command = " ".join(["python -m filinglens.extract.synthetic_qa", *argv])

    if args.command == "prepare":
        import pandas as pd

        tasks, stats = prepare(pd.read_parquet(args.corpus), pd.read_csv(args.splits))
        write_jsonl(tasks, TASKS)
        stats = {"command": command, "seed": SEED, "per_cell": PER_CELL, **stats}
        (WORK / "prepare.json").write_text(json.dumps(stats, indent=2) + "\n")
        print(json.dumps(stats, indent=2))
        return

    if args.command == "generate":
        from filinglens.extract.silver_label import PeakGpuMemory, slug

        tasks = read_jsonl(TASKS)[: args.limit]
        started = time.perf_counter()
        with PeakGpuMemory() as peak:
            raws = generate(tasks, args, PROMPT.read_text())
        elapsed = round(time.perf_counter() - started, 1)
        name = slug(args.model) + (f"-first{args.limit}" if args.limit else "")
        rows = [{"task_no": t["task_no"], "raw": r} for t, r in zip(tasks, raws, strict=True)]
        write_jsonl(rows, WORK / f"qa_raw_{name}.jsonl")
        run = {
            "command": command,
            "finished_utc": datetime.now(UTC).isoformat(timespec="seconds"),
            "model": args.model,
            "quantization": args.quantization,
            "gpu_memory_utilization": args.gpu_memory_utilization,
            "enforce_eager": args.enforce_eager,
            "tasks": len(tasks),
            "elapsed_s_incl_model_load": elapsed,
            "peak_gpu_memory_mib": peak.peak_mib,
        }
        if not args.limit:  # only full runs are evidence
            Path("bench/synthetic_qa_run.json").write_text(json.dumps(run, indent=2) + "\n")
        print(json.dumps(run, indent=2))
        if args.limit:  # smoke test: show the first answers
            for t, r in zip(tasks, raws, strict=True):
                print(t["ticker"], t["period_year"], json.dumps(check_task(t, r), indent=1)[:1500])
        return

    import pandas as pd

    from filinglens.extract.silver_label import slug

    tasks = read_jsonl(TASKS)
    raw_path = WORK / f"qa_raw_{slug(args.model)}.jsonl"
    raws = {r["task_no"]: r["raw"] for r in read_jsonl(raw_path)}
    kept, checked = build_rows(tasks, raws, args.model)
    splits = pd.read_csv(args.splits)
    corpus = pd.read_parquet(args.corpus, columns=["cik", "text"])
    held = set(splits.loc[splits["split"] != "train", "cik"].astype(int))
    held_keys = set(corpus.loc[corpus["cik"].isin(held), "text"].map(text_key))
    train = set(splits.loc[splits["split"] == "train", "cik"].astype(int))
    leaks = leakage(kept, train, held_keys, {t["para_id"]: t for t in tasks})
    if any(leaks.values()):
        raise SystemExit(f"leakage test failed, nothing written: {leaks}")
    write_jsonl(checked, WORK / "qa_checked.jsonl")
    write_jsonl(kept, OUTPUT)
    stats = {
        "command": command,
        "finished_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "generator": args.model,
        "prompt": str(PROMPT),
        "prompt_version": PROMPT_VERSION,
        "prepare": json.loads((WORK / "prepare.json").read_text()),
        "pairs_generated": len(checked),
        "pairs_kept": len(kept),
        "kept_rate": round(len(kept) / len(checked), 4) if checked else None,
        "problems": dict(Counter(p for c in checked for p in c["problems"]).most_common()),
        "pairs_with_any_problem": sum(bool(c["problems"]) for c in checked),
        "kept_by_type": dict(Counter(r["type"] for r in kept).most_common()),
        "kept_by_sector": dict(sorted(Counter(r["sector"] for r in kept).items())),
        "kept_companies": len({r["cik"] for r in kept}),
        "kept_paragraphs": len({r["para_id"] for r in kept}),
        "leakage": leaks,
        "output": str(OUTPUT),
    }
    Path("bench/synthetic_qa.json").write_text(json.dumps(stats, indent=2) + "\n")
    print(json.dumps({k: v for k, v in stats.items() if k != "prepare"}, indent=2))


if __name__ == "__main__":
    main()
